"""Build an index of every name registered into the DirectAI brain by sw.sword.

Usage: python -I build_dec_index.py <sw.sword root> <sw.models root> <sw.soult root> <out.md>
"""
import os
import re
import subprocess
import sys
from collections import Counter, defaultdict

sword, models, soult, out = sys.argv[1:5]
sim = os.path.join(sword, "src", "libraries", "simulation")
integ = os.path.join(sword, "data", "app-data", "resources", "integration")


def stamp(repo):
    """(branch, short commit, commit date) of a checkout; '?' when git fails."""
    def git(*args):
        try:
            return subprocess.run(["git", "-C", repo, *args], capture_output=True, text=True, check=True).stdout.strip()
        except (OSError, subprocess.CalledProcessError):
            return "?"
    return git("branch", "--show-current") or "(detached)", git("rev-parse", "--short=10", "HEAD"), git("log", "-1", "--format=%cs", "HEAD")

REG = re.compile(r'\bRegister(Function|Method)\s*(<[^;"]*?>)?\s*\(\s*"([A-Za-z0-9_]+)"\s*,\s*', re.S)

entries = []  # (name, kind, relpath, line, target, family)
for root, _, files in os.walk(sim):
    for f in files:
        if not f.endswith(".cpp"):
            continue
        p = os.path.join(root, f)
        txt = open(p, encoding="utf-8", errors="replace").read()
        for m in REG.finditer(txt):
            line = txt.count("\n", 0, m.start()) + 1
            # target: text until the matching close paren of the Register call (approx: up to ');' )
            rest = txt[m.end():m.end() + 400]
            depth, buf = 1, []
            for ch in rest:
                if ch == "(":
                    depth += 1
                elif ch == ")":
                    depth -= 1
                    if depth == 0:
                        break
                buf.append(ch)
            target = " ".join("".join(buf).split())
            if len(target) > 90:
                target = target[:87] + "..."
            rel = os.path.relpath(p, sword).replace("\\", "/")
            entries.append((m.group(3), m.group(1), rel, line, target))


def scan_lua(base, subdirs_filter=None):
    """Return Counter of identifier tokens and per-name file sets for .lua files under base."""
    tok = re.compile(r"\b_?[A-Za-z][A-Za-z0-9_]*\b")
    counts, where = Counter(), defaultdict(set)
    if not os.path.isdir(base):
        return counts, where
    for root, _, files in os.walk(base):
        for f in files:
            if not f.endswith(".lua"):
                continue
            p = os.path.join(root, f)
            try:
                txt = open(p, encoding="utf-8", errors="replace").read()
            except OSError:
                continue
            for t in tok.findall(txt):
                counts[t] += 1
                where[t].add(f)
    return counts, where


names = {e[0] for e in entries}
ic, iw = scan_lua(integ)
mc, _ = scan_lua(os.path.join(models, "data", "data", "models"))
sc, _ = scan_lua(os.path.join(soult, "data", "data", "models"))

decfile = os.path.join(models, "data", "data", "models", "decfunctions.txt")
declared = set()
if os.path.exists(decfile):
    declared = {l.strip() for l in open(decfile, encoding="utf-8", errors="replace") if l.strip() and not l.startswith("#")}

byfile = defaultdict(list)
for e in entries:
    byfile[e[2]].append(e)

L = []
L.append("# sw.sword — Brain function index (generated)\n")
L.append("Every name registered into the DirectAI Lua brain by the C++ kernel "
         "(`brain.RegisterFunction` / `brain.RegisterMethod` in `src/libraries/simulation`).\n")
sb, sh, sd = stamp(sword)
mb, mh, _ = stamp(models)
ob, oh, _ = stamp(soult)
L.append(f"Generated by `forge/tools/build_dec_index.py` from sw.sword **`{sb}` @ `{sh}`** ({sd}); usage counts from "
         f"sw.models `{mb}` @ `{mh}` and sw.soult `{ob}` @ `{oh}`. Regenerate after pulling; line numbers drift.\n")
L.append("**Stale check:** if `git -C C:/MASARepo/sw.sword rev-parse --short=10 HEAD` differs from the commit above, "
         "line numbers and counts are hints only: confirm with grep. **Grep this file, never read it whole.**\n")
L.append("Columns: **Int** = occurrences in `data/app-data/resources/integration/*.lua`; "
         "**Models** = occurrences in sw.models `data/data/models/**/*.lua`; **Soult** = same in sw.soult; "
         "**txt** = listed in sw.models `decfunctions.txt` (used by `ant checkdec`). "
         "Names starting with `_DEC_` take `myself` (the agent's decision object) and are normally wrapped by a "
         "same-name-without-underscore Lua function in `DECFunctionWrappers.lua`; Lua code should call the wrapper.\n")
L.append(f"\nTotal registrations: {len(entries)} — distinct names: {len(names)}\n")
dups = [n for n, c in Counter(e[0] for e in entries).items() if c > 1]
if dups:
    L.append(f"\nNames registered more than once ({len(dups)}; same name bound in several places — last registration wins at runtime, check call order): "
             + ", ".join(f"`{d}`" for d in sorted(dups)) + "\n")

L.append("\n## Registrations per file\n\n| File | Count |\n|---|---|\n")
for f in sorted(byfile, key=lambda k: -len(byfile[k])):
    L.append(f"| `{f}` | {len(byfile[f])} |\n")

unused = sorted(n for n in names if ic[n] == 0 and mc[n] == 0 and sc[n] == 0
                and ic[n.lstrip('_')] == 0 and mc[n.lstrip('_')] == 0)
L.append(f"\n## Apparently unused names ({len(unused)})\n\nNot found (nor their `_`-stripped wrapper) in integration, sw.models or sw.soult Lua. "
         "Candidates for dead code — or used only via dynamic strings / other model repos.\n\n")
L.append(", ".join(f"`{n}`" for n in unused) + "\n")

for f in sorted(byfile):
    L.append(f"\n## `{f}`\n\n| Name | Kind | Line | Bound to | Int | Models | Soult | txt |\n|---|---|---|---|---|---|---|---|\n")
    for name, kind, rel, line, target in sorted(byfile[f], key=lambda e: e[3]):
        t = target.replace("|", "\\|")
        L.append(f"| `{name}` | {kind[0]} | [{line}](../../../sw.sword/{rel}#L{line}) | `{t}` | {ic[name] or ''} | {mc[name] or ''} | {sc[name] or ''} | {'y' if name in declared else ''} |\n")

os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, "w", encoding="utf-8").write("".join(L))
print(len(entries), "registrations,", len(names), "names,", len(unused), "unused,", len(dups), "dups")
